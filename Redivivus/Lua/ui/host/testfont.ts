export interface BuiltFont {
    sprite: Sprite;
    advance: number[];
    frameOf: number[];
    lineHeight: number;
    ascent: number;
    has: boolean[];
}

/** White index used for glyph pixels before the colour remap; chosen by the caller's palette. */
export function buildTestFont(name: string, white: number): BuiltFont | undefined {
    const m = testFonts.find((f) => f.name === name);
    if (m === undefined) return undefined;
    const scale = m.advance / 6;
    const frames: Frame[] = [];
    const advance: number[] = new Array(256).fill(0);
    const frameOf: number[] = new Array(256).fill(-1);
    const has: boolean[] = new Array(256).fill(false);
    for (let code = m.first; code <= m.last; code++) {
        const w = 5 * scale;
        const h = 7 * scale;
        const pixels = new Uint8Array(w * h);
        const mask = new Uint8Array(w * h);
        for (let col = 0; col < 5; col++) {
            const bits = GLYPHS[(code - 32) * 5 + col];
            for (let row = 0; row < 7; row++) {
                if ((bits >> row) & 1)
                    for (let sy = 0; sy < scale; sy++)
                        for (let sx = 0; sx < scale; sx++) {
                            const i = (row * scale + sy) * w + col * scale + sx;
                            pixels[i] = white;
                            mask[i] = 1;
                        }
            }
        }
        frameOf[code] = frames.length;
        frames.push({ width: w, height: h, offsetX: 0, offsetY: 0, pixels, mask });
        advance[code] = m.advance;
        has[code] = true;
    }
    return { sprite: { directions: 1, frames }, advance, frameOf, lineHeight: m.lineHeight, ascent: m.ascent, has };
}
