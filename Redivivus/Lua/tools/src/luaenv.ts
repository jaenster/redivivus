// The Lua standard library as a mod sees it, for TypeScript: lua-types' LuaJIT declarations with
// everything the sandbox removes taken out, so using it is a compile error rather than a nil at
// run time. Written to Redivivus/Lua/api/lua/ by gen.ts (and checked by gen.ts --check).
//
// What a mod environment holds (d2_lua_host.cpp): the base functions below, copies of string
// (without dump), table, math, bit and coroutine, text-only load/loadstring, and
// collectgarbage("count"). Gone: io, os, debug, package, require (the host's require is reached
// through import), dofile, loadfile, getfenv, setfenv, newproxy, module, rawlen, jit, ffi,
// string.dump and every other collectgarbage option.

import * as fs from "node:fs";
import * as path from "node:path";
import ts from "typescript";

const TOOLS = path.resolve(import.meta.dirname, "..");
const LUA_TYPES = path.join(TOOLS, "node_modules/lua-types");

// The files lua-types/jit.d.ts pulls in, in its order.
const SOURCES = [
    "core/coroutine.d.ts", "core/global.d.ts", "core/math.d.ts", "core/metatable.d.ts", "core/string.d.ts",
    "core/table.d.ts", "special/5.1-or-jit.d.ts", "special/5.2-plus-or-jit.d.ts", "special/5.3-pre.d.ts",
    "special/5.4-pre.d.ts", "special/jit-only.d.ts",
];

const GLOBAL_FUNCTIONS = new Set([
    "assert", "collectgarbage", "error", "getmetatable", "ipairs", "load", "loadstring", "next", "pairs", "pcall",
    "print", "rawequal", "rawget", "rawset", "select", "setmetatable", "tonumber", "tostring", "type", "unpack", "xpcall",
]);
const GLOBAL_VARIABLES = new Set(["_G", "_VERSION"]);
// bit is left out: TypeScriptToLua reserves the name (it compiles &, | and friends to bit.*).
const NAMESPACES = new Set(["string", "table", "math", "coroutine"]);
const NAMESPACE_MEMBERS_REMOVED = new Set(["string.dump"]);

function keepFunction(fn: ts.FunctionDeclaration): boolean {
    const name = fn.name?.text ?? "";
    if (!GLOBAL_FUNCTIONS.has(name)) return false;
    // Only collectgarbage("count") is left to mods.
    if (name === "collectgarbage") return fn.parameters[0]?.type?.getText() === "'count'";
    return true;
}

function emitFile(rel: string): string {
    const file = path.join(LUA_TYPES, rel);
    const text = fs.readFileSync(file, "utf8");
    const sf = ts.createSourceFile(file, text, ts.ScriptTarget.ESNext, true);
    const out: string[] = [];
    const head = text.slice(0, sf.statements[0]?.getFullStart() ?? text.length);
    // References between lua-types' own files are replaced by the index; lib references stay.
    out.push(head.split("\n").filter((l) => !/^\/\/\/ <reference (path|types)=/.test(l)).join("\n").trimEnd());
    for (const st of sf.statements) {
        const full = text.slice(st.getFullStart(), st.end);
        if (ts.isFunctionDeclaration(st)) {
            if (keepFunction(st)) out.push(full);
        } else if (ts.isVariableStatement(st)) {
            if (st.declarationList.declarations.every((d) => GLOBAL_VARIABLES.has(d.name.getText()))) out.push(full);
        } else if (ts.isModuleDeclaration(st)) {
            const ns = st.name.getText();
            if (!NAMESPACES.has(ns) || !st.body || !ts.isModuleBlock(st.body)) continue;
            const members = st.body.statements.filter((m) => {
                const name = ts.isFunctionDeclaration(m) ? m.name?.text : ts.isVariableStatement(m) ? m.declarationList.declarations[0].name.getText() : undefined;
                return !name || !NAMESPACE_MEMBERS_REMOVED.has(`${ns}.${name}`);
            });
            if (!members.length) continue;
            const open = text.slice(st.getFullStart(), st.body.statements.pos);
            out.push(open + members.map((m) => text.slice(m.getFullStart(), m.end)).join("") + text.slice(st.body.statements.end, st.end));
        } else {
            out.push(full); // types and interfaces
        }
    }
    return out.join("") + "\n";
}

// Every output file of the trimmed environment, by absolute path.
export function luaEnvTypings(outDir: string): Map<string, string> {
    const license = fs.readFileSync(path.join(LUA_TYPES, "LICENSE"), "utf8").trim().split("\n").map((l) => `// ${l}`.trimEnd());
    const banner = [
        "// Generated by Redivivus/Lua/tools/src/gen.ts from lua-types 2.14.1 (LuaJIT), trimmed to what the",
        "// mod sandbox offers (see tools/src/luaenv.ts). Do not edit.",
        "//",
        ...license,
        "",
    ].join("\n");
    const outputs = new Map<string, string>();
    const index: string[] = [
        "// The Lua standard library a mod has. Generated by Redivivus/Lua/tools/src/gen.ts; do not edit.",
        '/// <reference types="@typescript-to-lua/language-extensions" />',
    ];
    for (const rel of SOURCES) {
        const name = rel.replace(/\//g, "-");
        outputs.set(path.join(outDir, name), banner + emitFile(rel));
        index.push(`/// <reference path="./${name}" />`);
    }
    outputs.set(path.join(outDir, "index.d.ts"), index.join("\n") + "\n");
    return outputs;
}
