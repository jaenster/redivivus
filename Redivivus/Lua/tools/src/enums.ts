// Engine enums for mods: the enums core/engine-enums.json names, read from the tree's
// Source/D2Headers/d2_enums.h, written as core/redivivus/engine-enums.ts (re-exported by
// redivivus:enums). TypeScript inlines the values, plain Lua gets read-only tables, LuaLS and the
// reference list them, and the glue static_asserts every value against the C++ constant, so a
// header that moves a value fails the build until the generator runs again.
//
// The header's form, one block per enum:
//   typedef uint32_t eD2UnitType;
//   namespace eD2UnitType_ns {
//   constexpr eD2UnitType UNIT_PLAYER = 0;
//   ...
//   }

import * as fs from "node:fs";
import * as path from "node:path";

type Entry = { cpp: string; ts: string; doc?: string; exclude?: string[]; rename?: Record<string, string>; prefix?: string };
type AllowList = { exported: Entry[]; leftOut: Record<string, string> };
type CppEnum = { name: string; members: { name: string; value: number }[] };

export class EnumError extends Error {}

export function readHeader(file: string): Map<string, CppEnum> {
    const out = new Map<string, CppEnum>();
    const lines = fs.readFileSync(file, "utf8").split("\n");
    let current: CppEnum | undefined;
    for (const line of lines) {
        const open = /^namespace (\w+)_ns \{$/.exec(line);
        if (open) {
            current = { name: open[1], members: [] };
            out.set(open[1], current);
            continue;
        }
        if (!current) continue;
        if (line === "}") {
            current = undefined;
            continue;
        }
        const m = /^constexpr (\w+) (\w+) = (-?\d+);$/.exec(line);
        if (m && m[1] === current.name) current.members.push({ name: m[2], value: Number(m[3]) });
    }
    return out;
}

// UNIT_PLAYER -> Player, UNITSTAT_item_armor_percent -> ItemArmorPercent, QUEST_DenOfEvil -> DenOfEvil.
export function memberName(cpp: string, prefix: string): string {
    return cpp.slice(prefix.length).split("_").filter((p) => p.length).map((p) =>
        /[a-z]/.test(p) ? p[0].toUpperCase() + p.slice(1) : p[0] + p.slice(1).toLowerCase()).join("");
}

// The longest common prefix of the names that ends in an underscore.
export function commonPrefix(names: string[]): string {
    if (names.length < 2) return names.length ? names[0].slice(0, names[0].indexOf("_") + 1) : "";
    let p = names[0];
    for (const n of names) while (!n.startsWith(p)) p = p.slice(0, -1);
    return p.slice(0, p.lastIndexOf("_") + 1);
}

function docLines(text: string, indent: string): string[] {
    return ["/**", ...text.split("\n").map((l) => ` * ${l}`.trimEnd()), " */"].map((l) => indent + l.replace(/^\/\*\*$/, "/**"));
}

export function engineEnums(allowFile: string, headerFile: string, root: string): string {
    const allow = JSON.parse(fs.readFileSync(allowFile, "utf8")) as AllowList;
    const header = readHeader(headerFile);
    const where = path.relative(root, allowFile);
    const tsNames = new Set<string>();
    for (const name of Object.keys(allow.leftOut)) {
        if (!header.has(name)) throw new EnumError(`${where}: leftOut names ${name}, which ${path.relative(root, headerFile)} does not have`);
    }
    const out: string[] = [
        "/**",
        " * Engine enums, generated by Redivivus/Lua/tools/src/gen.ts from Source/D2Headers/d2_enums.h and the",
        " * allow-list core/engine-enums.json. Do not edit. The values are the engine's.",
        " * @side data server client",
        ' * @assertInclude "Source/D2Headers/d2_enums.h"',
        " */",
    ];
    for (const e of allow.exported) {
        const cpp = header.get(e.cpp);
        if (!cpp) throw new EnumError(`${where}: ${e.cpp} is not an enum of ${path.relative(root, headerFile)}`);
        if (allow.leftOut[e.cpp]) throw new EnumError(`${where}: ${e.cpp} is both exported and left out`);
        if (!/^[A-Z][A-Za-z0-9]*$/.test(e.ts)) throw new EnumError(`${where}: ${e.cpp}: '${e.ts}' is not a PascalCase name`);
        if (tsNames.has(e.ts)) throw new EnumError(`${where}: two enums are called ${e.ts}`);
        tsNames.add(e.ts);
        for (const x of [...(e.exclude ?? []), ...Object.keys(e.rename ?? {})]) {
            if (!cpp.members.some((m) => m.name === x)) throw new EnumError(`${where}: ${e.cpp} has no member ${x}`);
        }
        const members = cpp.members.filter((m) => !(e.exclude ?? []).includes(m.name));
        const prefix = e.prefix ?? commonPrefix(members.map((m) => m.name));
        const seen = new Map<string, string>();
        out.push("");
        out.push(...docLines(`${e.doc ?? e.ts}\nC++ ${e.cpp}.\n@native ${e.cpp}\n@scope ${e.cpp}_ns`, ""));
        out.push(`export const enum ${e.ts} {`);
        for (const m of members) {
            const name = e.rename?.[m.name] ?? memberName(m.name, prefix);
            if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
                throw new EnumError(`${where}: ${e.cpp}.${m.name} gives '${name}', not an identifier; give it a name in 'rename' or 'exclude' it`);
            }
            const prev = seen.get(name);
            if (prev) throw new EnumError(`${where}: ${e.cpp}.${m.name} and ${prev} both become ${e.ts}.${name}; give one a name in 'rename'`);
            seen.set(name, m.name);
            out.push(`    /** @native ${m.name} */`);
            out.push(`    ${name} = ${m.value},`);
        }
        out.push("}");
    }
    return out.join("\n") + "\n";
}
