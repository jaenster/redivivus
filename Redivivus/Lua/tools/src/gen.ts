// The generator: everything in Redivivus/Lua that is made from other files, written or checked.
//
//   node src/gen.ts            write every output
//   node src/gen.ts --check    write nothing; fail when an output on disk differs from what its
//                              sources give (a stale commit)
//
// Outputs, and what each is made from:
//   api/lua/*.d.ts                      lua-types, trimmed to the sandbox (luaenv.ts)
//   core/redivivus/engine-enums.ts      Source/D2Headers/d2_enums.h and core/engine-enums.json (enums.ts)
//   generated/d2_lua_core.gen.cpp       the core compiled to Lua and embedded, with the table of
//                                       public modules the resolver serves (core.ts)
//   api/redivivus/*.d.ts, api/native/*  the public modules' declarations, emitted by the compiler
//   api/ui/*.d.ts                       the UI kit's declarations, which redivivus:ui re-exports
//   generated/d2_lua_api_main.gen.*     the native glue: core/native/core.d.ts and the core's enums,
//                                       events and registries (glue.ts)
//   test/generated/d2_lua_api_test.gen.*  the host test's glue: core/native/testworld.d.ts
//   api/docs/reference.md, api/luals/   the reference and LuaLS files, from the emitted declarations
//   api/ls-plugin/                      the editor plugin, compiled to CommonJS
//   generated/d2_lua_builtin.gen.cpp    the built-in redivivus mod's program (builtin/), compiled as a
//                                       mod is, against the api declarations above (written first)
// The C++ is committed, so a build needs no Node; the build runs --check when Node is there.

import * as fs from "node:fs";
import * as path from "node:path";
import ts from "typescript";
import { compileBuiltin } from "./cli.ts";
import { buildCore, cLiteral, CORE, CoreError, coreFiles, coreOptions } from "./core.ts";
import { LUARC, luals, lualsPath, reference } from "./docs.ts";
import { EnumError, engineEnums } from "./enums.ts";
import { emitCpp, GenError, loadSet, type SetConfig } from "./glue.ts";
import { luaEnvTypings } from "./luaenv.ts";

const TOOLS = path.resolve(import.meta.dirname, "..");
const LUA = path.resolve(TOOLS, "..");
const ROOT = path.resolve(LUA, "../..");
const API = path.join(LUA, "api");
const LUA_ENV = path.join(API, "lua/index.d.ts");

function publicSources(): string[] {
    return fs.readdirSync(path.join(CORE, "redivivus")).filter((f) => f.endsWith(".ts")).sort().map((f) => path.join(CORE, "redivivus", f));
}

const SETS: SetConfig[] = [
    {
        name: "main",
        bind: [path.join(CORE, "native/core.d.ts"), ...publicSources()],
        cpp: path.join(LUA, "generated/d2_lua_api_main.gen.cpp"),
        header: path.join(LUA, "generated/d2_lua_api_main.gen.h"),
    },
    {
        name: "test",
        bind: [path.join(CORE, "native/testworld.d.ts")],
        cpp: path.join(LUA, "test/generated/d2_lua_api_test.gen.cpp"),
        header: path.join(LUA, "test/generated/d2_lua_api_test.gen.h"),
    },
];

// The language service plugin (lsplugin.ts and the checks it shares with the build), as CommonJS
// for tsserver, in the api package.
function lsPluginOutputs(): Map<string, string> {
    const out = new Map<string, string>();
    for (const name of ["lsplugin", "scriptcheck"]) {
        const source = fs.readFileSync(path.join(TOOLS, "src", `${name}.ts`), "utf8");
        const js = ts.transpileModule(source, {
            compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, rewriteRelativeImportExtensions: true },
            fileName: `${name}.ts`,
        }).outputText;
        const banner = `// Generated from Redivivus/Lua/tools/src/${name}.ts by Redivivus/Lua/tools/src/gen.ts. Do not edit.\n`;
        out.set(path.join(API, "ls-plugin", name === "lsplugin" ? "index.js" : "scriptcheck.js"), banner + js);
    }
    return out;
}

function filesUnder(dir: string): string[] {
    if (!fs.existsSync(dir)) return [];
    const out: string[] = [];
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, e.name);
        if (e.isDirectory()) out.push(...filesUnder(full));
        else out.push(full);
    }
    return out;
}

// The built-in mod's Lua, by path in its namespace, as C++.
function builtinCpp(files: Map<string, string>): string {
    const cpp: string[] = [
        "// Generated by Redivivus/Lua/tools/src/gen.ts from Redivivus/Lua/builtin (the game's own redivivus mod,",
        "// compiled as a mod is). Do not edit; change the sources and run the generator.",
        "#if D2_FEATURE_MODS",
        '#include "Redivivus/Lua/d2_lua_core.h"',
        "",
    ];
    const names = [...files.keys()].sort();
    names.forEach((name, i) => cpp.push(`// ${name}`, `static const char kFile${i}[] =`, ...cLiteral(files.get(name)!), "    ;", ""));
    cpp.push("const D2LuaCoreChunk g_aD2LuaBuiltinFiles[] = {");
    names.forEach((name, i) => cpp.push(`    { ${JSON.stringify(name)}, kFile${i}, sizeof(kFile${i}) - 1 },`));
    cpp.push("    { nullptr, nullptr, 0 },", "};", "#endif", "");
    return cpp.join("\n");
}

function main(): number {
    const check = process.argv.includes("--check");
    const outputs = new Map<string, string>();
    try {
        // The core and the glue read these, so without --check they are written first.
        const early = luaEnvTypings(path.join(API, "lua"));
        early.set(path.join(CORE, "redivivus/engine-enums.ts"), engineEnums(path.join(CORE, "engine-enums.json"), path.join(ROOT, "Source/D2Headers/d2_enums.h"), ROOT));
        for (const [file, text] of early) {
            outputs.set(file, text);
            if (!check && (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text)) {
                fs.mkdirSync(path.dirname(file), { recursive: true });
                fs.writeFileSync(file, text);
                console.log(`gen: wrote ${path.relative(ROOT, file)}`);
            }
        }
        const core = buildCore(LUA_ENV);
        for (const [file, text] of core.outputs) outputs.set(file, text);

        const files = coreFiles();
        const program = ts.createProgram([LUA_ENV, ...files], { ...coreOptions(), noEmit: true });
        for (const config of SETS) {
            const set = loadSet(config, program, files.filter((f) => f.endsWith(".ts")));
            const { cpp, header, asserts } = emitCpp(set);
            if (asserts) outputs.set(config.cpp.replace(/\.gen\.cpp$/, "_asserts.gen.cpp"), asserts);
            outputs.set(config.cpp, cpp);
            outputs.set(config.header, header);
        }

        const decls = core.modules.map((m) => {
            const text = core.outputs.get(path.join(API, "redivivus", `${m.entry}.d.ts`));
            if (text === undefined) throw new CoreError(`no declarations were emitted for redivivus:${m.entry}`);
            return { entry: m.entry, sides: m.sides, grant: m.grant, text };
        });
        outputs.set(path.join(API, "docs/reference.md"), reference(decls));
        for (const d of decls) outputs.set(lualsPath(path.join(API, "luals"), d.entry), luals(d));
        outputs.set(path.join(API, "luals/.luarc.json"), LUARC);
        for (const [file, text] of lsPluginOutputs()) outputs.set(file, text);
        // The licence of TypeScriptToLua's runtime library, which the embedded core carries.
        const license = fs.readFileSync(path.join(TOOLS, "node_modules/typescript-to-lua/LICENSE"), "utf8");
        outputs.set(path.join(LUA, "generated/lualib_bundle.LICENSE"),
            "The TypeScriptToLua runtime library (lualib_bundle.lua of typescript-to-lua 1.37.1), embedded in\n"
            + "d2_lua_core.gen.cpp and served to mods as redivivus:lualib, is under this licence:\n\n" + license);
    } catch (e) {
        if (e instanceof GenError || e instanceof EnumError || e instanceof CoreError) {
            console.error(`gen: ${e.message}`);
            return 1;
        }
        throw e;
    }
    // The built-in mod compiles against the declarations: write them first (with --check they must
    // already be current, or they are reported stale below).
    try {
        if (!check) {
            for (const [file, text] of outputs) {
                if (!file.startsWith(API + path.sep)) continue;
                if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) continue;
                fs.mkdirSync(path.dirname(file), { recursive: true });
                fs.writeFileSync(file, text);
                console.log(`gen: wrote ${path.relative(ROOT, file)}`);
            }
        }
        outputs.set(path.join(LUA, "generated/d2_lua_builtin.gen.cpp"), builtinCpp(compileBuiltin(path.join(LUA, "builtin"))));
    } catch (e) {
        console.error(`gen: ${(e as Error).message}`);
        return 1;
    }
    let stale = 0;
    // Generated directories hold nothing else.
    for (const dir of [path.join(API, "redivivus"), path.join(API, "native"), path.join(API, "ui"), path.join(API, "luals"), path.join(API, "ls-plugin"), path.join(LUA, "generated")]) {
        for (const file of filesUnder(dir)) {
            if (outputs.has(file)) continue;
            if (check) {
                console.error(`gen: ${path.relative(ROOT, file)} is no output any more; remove it`);
                stale++;
            } else {
                fs.rmSync(file);
                console.log(`gen: removed ${path.relative(ROOT, file)}`);
            }
        }
    }
    for (const [file, text] of outputs) {
        const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;
        if (old === text) continue;
        if (check) {
            console.error(`gen: stale: ${path.relative(ROOT, file)} (run node Redivivus/Lua/tools/src/gen.ts)`);
            stale++;
        } else {
            fs.mkdirSync(path.dirname(file), { recursive: true });
            fs.writeFileSync(file, text);
            console.log(`gen: wrote ${path.relative(ROOT, file)}`);
        }
    }
    if (check) console.log(stale ? `gen: ${stale} stale output(s)` : `gen: ${outputs.size} outputs up to date`);
    return stale ? 1 : 0;
}

process.exit(main());
