// The reference (api/docs/reference.md) and the LuaLS annotations (api/luals/redivivus/*.lua) for
// plain-Lua authors, both written from the declarations the compiler emitted for the core's public
// modules: what the reference and the editor say is what the code is.
//
// LuaLS: each module is a ---@meta file named after its specifier (`---@meta redivivus:server`),
// which the LuaLS documentation describes as the name a definition file may be required by. LuaLS
// was not available to run here; the files also sit at redivivus/<entry>.lua, so the dot form
// LuaLS's runtime.path search uses (require "redivivus.server") would find them too.

import * as path from "node:path";
import ts from "typescript";

export type ModuleDecl = { entry: string; sides: string[]; grant: string; text: string };

function jsdoc(node: ts.Node): string {
    const parts: string[] = [];
    for (const d of ts.getJSDocCommentsAndTags(node)) {
        if (ts.isJSDoc(d)) {
            const t = ts.getTextOfJSDocComment(d.comment);
            if (t) parts.push(t.trim());
        }
    }
    return parts.join("\n");
}

function oneLine(s: string): string {
    return s.replace(/\/\*\*[\s\S]*?\*\/\s*/g, "").replace(/\s+/g, " ").trim();
}

function exported(st: ts.Statement): boolean {
    return !!(ts.canHaveModifiers(st) && ts.getModifiers(st)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword));
}

type Item = { kind: string; name: string; sig: string; doc: string; members: { name: string; sig: string; doc: string; value?: string }[] };

function items(text: string, file: string): { items: Item[]; reexports: string[] } {
    const sf = ts.createSourceFile(file, text, ts.ScriptTarget.ESNext, true);
    const out: Item[] = [];
    const reexports: string[] = [];
    for (const st of sf.statements) {
        if (ts.isExportDeclaration(st)) {
            reexports.push(oneLine(st.getText()));
            continue;
        }
        if (!exported(st)) continue;
        if (ts.isFunctionDeclaration(st) && st.name) {
            out.push({ kind: "function", name: st.name.text, sig: oneLine(st.getText()).replace(/^export (declare )?/, ""), doc: jsdoc(st), members: [] });
        } else if (ts.isVariableStatement(st)) {
            for (const d of st.declarationList.declarations) {
                out.push({ kind: "const", name: d.name.getText(), sig: `${d.name.getText()}: ${oneLine(d.type?.getText() ?? "unknown")}`, doc: jsdoc(st), members: [] });
            }
        } else if (ts.isInterfaceDeclaration(st)) {
            out.push({
                kind: "interface", name: st.name.text, sig: `interface ${st.name.text}${st.typeParameters ? `<${st.typeParameters.map((p) => p.getText()).join(", ")}>` : ""}`,
                doc: jsdoc(st), members: st.members.map((m) => ({ name: m.name?.getText() ?? "", sig: oneLine(m.getText()), doc: jsdoc(m) })),
            });
        } else if (ts.isEnumDeclaration(st)) {
            out.push({
                kind: "enum", name: st.name.text, sig: `enum ${st.name.text}`, doc: jsdoc(st),
                members: st.members.map((m) => ({ name: m.name.getText(), sig: oneLine(m.getText()), doc: jsdoc(m), value: m.initializer?.getText() })),
            });
        } else if (ts.isTypeAliasDeclaration(st)) {
            out.push({ kind: "type", name: st.name.text, sig: oneLine(st.getText()).replace(/^export (declare )?/, ""), doc: jsdoc(st), members: [] });
        }
    }
    return { items: out, reexports };
}

export function reference(modules: ModuleDecl[]): string {
    const out: string[] = [
        "# Redivivus mod API reference",
        "",
        "Generated by `Redivivus/Lua/tools/src/gen.ts` from the declarations the compiler emitted for the core's",
        "public modules (`Redivivus/Lua/core/redivivus/*.ts`). Do not edit.",
        "",
        "Every module is imported: `import { log } from \"redivivus:shared\"` in TypeScript, `local shared =",
        "require(\"redivivus:shared\")` in Lua. A mod's control entry `main` exports `server(game)` and/or",
        "`client(client)`; everything a mod does in a game it registers through the object it receives.",
        "",
        "|Module|Resolves in|Needs|",
        "|-|-|-|",
        ...modules.map((m) => `|\`redivivus:${m.entry}\`|${m.sides.join(", ")}|${m.grant === "test" ? "the test runner" : m.grant === "driver" ? "a driver script" : "-"}|`),
        "",
    ];
    for (const m of modules) {
        const { items: list, reexports } = items(m.text, `${m.entry}.d.ts`);
        out.push(`## redivivus:${m.entry}`, "");
        if (reexports.length) out.push(...reexports.map((r) => `- \`${r}\``), "");
        for (const it of list) {
            if (it.kind === "enum" && it.members.length > 48) {
                out.push(`### \`${it.sig}\``, "", ...(it.doc ? [it.doc, ""] : []), `${it.members.length} members: ${it.members.slice(0, 12).map((x) => `\`${x.sig}\``).join(", ")}, ...`, "");
                continue;
            }
            out.push(`### \`${it.sig}\``, "");
            if (it.doc) out.push(it.doc, "");
            for (const mem of it.members) out.push(`- \`${mem.sig}\`${mem.doc ? ` - ${mem.doc.replace(/\n/g, " ")}` : ""}`);
            if (it.members.length) out.push("");
        }
    }
    out.push("## storage", "",
        "A mod's `game.storage` is saved with the game. It holds booleans, numbers, strings, tables without a",
        "metatable, and handles; keys are strings, numbers or booleans. Shared tables and cycles are kept.",
        "Functions, coroutines and other userdata are refused with the path of the value in the error.", "");
    return out.join("\n");
}

function luaType(ts: string, known: Set<string>): string {
    let t = ts.trim();
    let optional = false;
    if (/\|\s*undefined$/.test(t)) {
        optional = true;
        t = t.replace(/\|\s*undefined$/, "").trim();
    }
    let out: string;
    if (/^(string|number|boolean|integer)$/.test(t)) out = t;
    else if (t === "void") out = "nil";
    else if (/\[\]$/.test(t) || /^Record</.test(t) || t.startsWith("{")) out = "table";
    else if (t.includes("=>")) out = "function";
    else if (known.has(t.replace(/<.*$/, ""))) out = t.replace(/<.*$/, "");
    else out = "any";
    return optional ? `${out}?` : out;
}

export function luals(m: ModuleDecl): string {
    const { items: list } = items(m.text, `${m.entry}.d.ts`);
    const known = new Set(list.filter((i) => i.kind === "interface" || i.kind === "enum").map((i) => i.name));
    const out: string[] = ["---@meta " + `redivivus:${m.entry}`, `-- redivivus:${m.entry}. Generated by Redivivus/Lua/tools/src/gen.ts from the emitted declarations; do not edit.`, ""];
    const doc = (d: string, indent = "") => (d ? d.split("\n").map((l) => `${indent}--- ${l}`) : []);
    for (const it of list.filter((i) => i.kind === "interface")) {
        out.push(...doc(it.doc), `---@class ${it.name}`);
        for (const mem of it.members) {
            const prop = /^(readonly\s+)?([\w$]+|\[[^\]]+\])\??\s*:\s*(.*?);?$/.exec(mem.sig);
            if (!mem.name || mem.name.startsWith("[")) continue;
            if (prop && !/^\w+\s*[<(]/.test(mem.sig.replace(/^readonly\s+/, ""))) out.push(`---@field ${mem.name} ${luaType(prop[3], known)} ${mem.doc.split("\n")[0]}`);
            else out.push(`---@field ${mem.name} function ${mem.doc.split("\n")[0]}`);
        }
        out.push("");
    }
    out.push("local M = {}", "");
    for (const it of list) {
        if (it.kind === "enum") {
            out.push(...doc(it.doc), `---@enum ${it.name}`, `M.${it.name} = {`);
            for (const mem of it.members) out.push(...doc(mem.doc, "    "), `    ${mem.name} = ${mem.value ?? "nil"},`);
            out.push("}", "");
        } else if (it.kind === "function") {
            const fn = ts.createSourceFile("x.ts", `declare ${it.sig}`, ts.ScriptTarget.ESNext, true).statements[0] as ts.FunctionDeclaration;
            const params = fn.parameters.filter((p) => p.name.getText() !== "this");
            out.push(...doc(it.doc));
            for (const p of params) {
                const name = p.dotDotDotToken ? "..." : p.name.getText();
                out.push(`---@param ${name}${p.questionToken ? "?" : ""} ${luaType(p.type?.getText() ?? "any", known)}`);
            }
            if (fn.type && fn.type.getText() !== "void") out.push(`---@return ${luaType(fn.type.getText(), known)}`);
            out.push(`function M.${it.name}(${params.map((p) => (p.dotDotDotToken ? "..." : p.name.getText())).join(", ")}) end`, "");
        } else if (it.kind === "const") {
            const type = it.sig.slice(it.sig.indexOf(":") + 1);
            out.push(...doc(it.doc), `---@type ${luaType(type, known)}`, `M.${it.name} = nil`, "");
        }
    }
    out.push("return M", "");
    return out.join("\n");
}

