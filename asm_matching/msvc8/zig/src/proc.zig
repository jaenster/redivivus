pub const Stat = impl.Stat;
pub const stat = impl.stat;
pub const statMtime = if (builtin.os.tag == .windows) void else impl.statMtime;
pub const statAtime = if (builtin.os.tag == .windows) void else impl.statAtime;
pub const writeAtomic = impl.writeAtomic;
pub const copyAtomic = impl.copyAtomic;
pub const listDir = impl.listDir;
pub const isLink = impl.isLink;
pub const WalkDir = impl.WalkDir;
pub const scanDir = impl.scanDir;
pub const walk = impl.walk;
pub const allFiles = impl.allFiles;
