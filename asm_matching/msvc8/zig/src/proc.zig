pub const sortStrings = impl.sortStrings;
pub const normpath = impl.normpath;
pub const joinNorm = impl.joinNorm;
pub const relpath = impl.relpath;
pub const realpath = impl.realpath;
pub const isSpace = impl.isSpace;
pub const strip = impl.strip;
pub const isWord = impl.isWord;
pub const lower = impl.lower;
pub const universalNewlines = impl.universalNewlines;
pub const splitlines = impl.splitlines;
pub const latin1ToUtf8 = impl.latin1ToUtf8;
